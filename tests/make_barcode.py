# CODE-128 (المجموعة C — رقمان لكل رمز)
# نستخدمه لأن باركودات المنتجات في النظام قد لا تُحقّق رقم تحقق
# EAN-13، بينما CODE-128 يقبل أي سلسلة أرقام.
# ============================================================
CODE128_PATTERNS = [
    "11011001100", "11001101100", "11001100110", "10010011000", "10010001100",
    "10001001100", "10011001000", "10011000100", "10001100100", "11001001000",
    "11001000100", "11000100100", "10110011100", "10011011100", "10011001110",
    "10111001100", "10011101100", "10011100110", "11001110010", "11001011100",
    "11001001110", "11011100100", "11001110100", "11101101110", "11101001100",
    "11100101100", "11100100110", "11101100100", "11100110100", "11100110010",
    "11011011000", "11011000110", "11000110110", "10100011000", "10001011000",
    "10001000110", "10110001000", "10001101000", "10001100010", "11010001000",
    "11000101000", "11000100010", "10110111000", "10110001110", "10001101110",
    "10111011000", "10111000110", "10001110110", "11101110110", "11010001110",
    "11000101110", "11011101000", "11011100010", "11011101110", "11101011000",
    "11101000110", "11100010110", "11101101000", "11101100010", "11100011010",
    "11101111010", "11001000010", "11110001010", "10100110000", "10100001100",
    "10010110000", "10010000110", "10000101100", "10000100110", "10110010000",
    "10110000100", "10011010000", "10011000010", "10000110100", "10000110010",
    "11000010010", "11001010000", "11110111010", "11000010100", "10001111010",
    "10100111100", "10010111100", "10010011110", "10111100100", "10011110100",
    "10011110010", "11110100100", "11110010100", "11110010010", "11011011110",
    "11011110110", "11110110110", "10101111000", "10100011110", "10001011110",
    "10111101000", "10111100010", "11110101000", "11110100010", "10111011110",
    "10111101110", "11101011110", "11110101110", "11010000100", "11010010000",
    "11010011100", "11000111010",
]
CODE128_STOP = "1100011101011"
CODE128_START_B = 104


def encode_code128_b(text: str) -> str:
    """
    يُرمّز أي نص ASCII مطبوع بمجموعة B من CODE-128.

    نستخدم المجموعة B لا C لأن C تعمل بأزواج أرقام، فتضطر لإضافة صفر
    بادئ عند الطول الفردي (13 رقمًا مثلًا) فيتغيّر الكود المقروء.
    """
    for ch in text:
        if not (32 <= ord(ch) <= 126):
            raise ValueError(f"حرف غير مدعوم في CODE-128B: {ch!r}")

    bits = CODE128_PATTERNS[CODE128_START_B]
    checksum = CODE128_START_B
    for pos, ch in enumerate(text, start=1):
        v = ord(ch) - 32                       # قيمة الرمز في المجموعة B
        bits += CODE128_PATTERNS[v]
        checksum += v * pos

    bits += CODE128_PATTERNS[checksum % 103]   # رمز التحقق
    bits += CODE128_STOP
    return bits


def render(code: str, path: str, w: int = 1280, h: int = 960,
           module: int = 6, bar_h: int = 420, symbology: str = "auto"):
    """
    يرسم الباركود في منتصف صورة بيضاء بحجم مناسب لإطار الكاميرا.

    symbology='auto' يحاول EAN-13 (إن كان رقم التحقق صحيحًا) وإلا
    يستخدم CODE-128 الذي يقبل أي سلسلة أرقام.
    """
    if symbology == "ean13":
        bits = encode_ean13(code)
    elif symbology == "code128":
        bits = encode_code128_b(code)
    else:
        try:
            bits = encode_ean13(code)
        except ValueError:
            bits = encode_code128_b(code)

    img = Image.new("RGB", (w, h), "white")
    d = ImageDraw.Draw(img)

    total_w = len(bits) * module
    x0 = (w - total_w) // 2
    y0 = (h - bar_h) // 2

    for i, bit in enumerate(bits):
        if bit == "1":
            x = x0 + i * module
            d.rectangle([x, y0, x + module - 1, y0 + bar_h], fill="black")

    img.save(path)
    return path


if __name__ == "__main__":
    code = sys.argv[1] if len(sys.argv) > 1 else "6941238701234"
    out = sys.argv[2] if len(sys.argv) > 2 else "/tmp/barcode.png"
    render(code, out)
    print(f"code={code}  ->  {out}")
