#!/usr/bin/env python3
"""
يُنشئ صورة باركود EAN-13 صالحة (بدون مكتبات خارجية) لاستخدامها في
اختبار قراءة الباركود بالكاميرا.

ترميز EAN-13 المُطبَّق هنا:
  - أول رقم يحدّد نمط التكافؤ (parity) للأرقام الستة الأولى (L أو G)
  - الأرقام الستة الثانية تُرمَّز بمجموعة R
  - حراس: 101 في البداية والنهاية، و01010 في الوسط
"""
import sys
from PIL import Image, ImageDraw

# مجموعات ترميز EAN-13
L = ["0001101", "0011001", "0010011", "0111101", "0100011",
     "0110001", "0101111", "0111011", "0110111", "0001011"]
G = ["0100111", "0110011", "0011011", "0100001", "0011101",
     "0111001", "0000101", "0010001", "0001001", "0010111"]
R = ["1110010", "1100110", "1101100", "1000010", "1011100",
     "1001110", "1010000", "1101000", "1001000", "1110100"]

# نمط التكافؤ للأرقام 2..7 حسب الرقم الأول
PARITY = ["LLLLLL", "LLGLGG", "LLGGLG", "LLGGGL", "LGLLGG",
          "LGGLLG", "LGGGLL", "LGLGLG", "LGLGGL", "LGGLGL"]


def check_digit(first12: str) -> str:
    total = sum(int(d) * (3 if i % 2 else 1) for i, d in enumerate(first12))
    return str((10 - total % 10) % 10)


def encode_ean13(code: str) -> str:
    if len(code) == 12:
        code += check_digit(code)
    if len(code) != 13 or not code.isdigit():
        raise ValueError(f"EAN-13 يجب أن يكون 13 رقمًا: {code!r}")
    if check_digit(code[:12]) != code[12]:
        raise ValueError(f"رقم التحقق غير صحيح في {code}")

    bits = "101"                                  # حارس البداية
    for i, ch in enumerate(code[1:7]):            # الأرقام 2..7
        bits += (L if PARITY[int(code[0])][i] == "L" else G)[int(ch)]
    bits += "01010"                               # حارس الوسط
    for ch in code[7:]:                           # الأرقام 8..13
        bits += R[int(ch)]
    bits += "101"                                 # حارس النهاية
    return bits


